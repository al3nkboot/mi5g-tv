import kotlin.test.assertEquals

// W4 definition of done: the report of protected packages found in default-disable groups,
// filed as data feedback (ARCHITECTURE 6.2), not a test failure. The rules here are the name
// rules of PLAN 6.5 plus SECURITY 8.5 as W4 reads them; the planner's `Protected` (W3) is the
// authority and adds the live rules (TIF inputs, persistent, active IME, current HOME). The
// report lands in core/spec/upstream-feedback/ and this test keeps it in step with the data.
class ProtectedReportTest {
    private val exact = setOf(
        "android", "com.android.systemui", "com.android.settings", "com.android.tv.settings", "com.android.packageinstaller",
        "com.google.android.packageinstaller", "com.android.permissioncontroller", "com.google.android.permissioncontroller",
        "com.android.providers.settings", "com.android.providers.tv", "com.android.providers.media", "com.android.providers.media.module",
        "com.android.shell", "com.android.adbd", "com.android.keychain", "com.android.se", "com.android.location.fused",
        "com.android.bluetooth", "com.google.android.gms", "com.google.android.gsf", "com.android.vending",
        "com.google.android.inputmethod.latin", "com.google.android.leanback.ime",
    )
    private val prefixes = listOf("com.android.networkstack", "com.android.wifi.", "com.droidlogic.")
    private val words = listOf(
        Regex("tvinput") to "a TV input service package by name", Regex("bluetooth") to "Bluetooth or remote pairing",
        Regex("autopair") to "remote pairing", Regex("(^|_)rcu(_|$)") to "remote control service", Regex("remotecontrol") to "remote control service",
    )

    private fun reason(pkg: PackageName, p: Profile): String? {
        val n = pkg.value
        return when {
            n in exact -> "PLAN 6.5 / SECURITY 8.5 denylist"
            prefixes.any { n.startsWith(it) } -> "denylist prefix ${prefixes.first { n.startsWith(it) }}"
            pkg == KnownLaunchers.SETUPWRAITH && Quirk.HOME_TAKEOVER_SETUPWRAITH !in p.quirks -> "setupwraith without the profile quirk"
            pkg in p.neverDisable -> "the same profile's never-disable list (its header says keep it)"
            pkg == p.liveTv -> "the profile's Live TV app"
            else -> words.firstOrNull { (w, _) -> n.split('.').drop(1).any { seg -> w.containsMatchIn(seg.lowercase()) } }?.let { "name looks like ${it.second}" }
        }
    }

    @Test fun reportProtectedPackagesInDisableGroups() {
        val rows = mutableListOf<String>()
        val w3 = mutableListOf<String>()
        var w3Available = true
        for (p in BundledProfileSource.bundled.profiles) for (g in p.groups.filter { it.default == GroupDefault.DISABLE }) for (e in g.packages) {
            reason(e.name, p)?.let { rows += "${p.id}\t${e.name.value}\t${g.id}\t$it" }
            if (w3Available) try {
                Protected.isProtected(e.name, null, p)?.let { w3 += "${p.id}\t${e.name.value}\t${g.id}\t$it" }
            } catch (_: NotImplementedError) {
                w3Available = false
            }
        }
        val text = buildString {
            append("# Packages upstream examples (commit ${BundledProfileSource.bundled.upstreamCommit}) list in a default-disable group\n")
            append("# that the app protects by name, so its plans skip them. Data feedback for upstream, not a failure.\n")
            append("# Generated by ProtectedReportTest from the W4 name rules (PLAN 6.5, SECURITY 8.5).\n")
            append("# folder\tpackage\tgroup\treason\n")
            rows.forEach { append(it).append('\n') }
        }
        println("BEGIN-REPORT\n" + text + "END-REPORT")
        val out = File(Fixtures.repoRoot, "core/spec/build/reports/upstream-feedback").apply { mkdirs() }
        File(out, "protected-in-disable-groups.txt").writeText(text)
        File(out, "protected-in-disable-groups-w3.txt").writeText(if (w3Available) w3.joinToString("\n", postfix = "\n") else "Protected is not implemented on this branch yet\n")
        val committed = File(Fixtures.repoRoot, "core/spec/upstream-feedback/protected-in-disable-groups.txt")
        if (committed.isFile) assertEquals(committed.readText(), text, "the report is out of date; copy build/reports/upstream-feedback/ over it")
    }
}
