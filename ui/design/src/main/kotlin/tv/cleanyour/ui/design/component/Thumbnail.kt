// The live TV thumbnail (check screen, Working, Manage): shape.medium, rim, 16:9, labelled
// "Live from the TV". A new frame crossfades in over 150 ms (D32, no shimmer). With no frame it
// shows a quiet TV placeholder; the screen says why in words. contentDescription is generated by
// W8 from the probe ("The TV shows the new home screen with four apps in the dock").
@Composable
fun TvThumbnail(
    image: ImageBitmap?,
    contentDescription: String,
    modifier: Modifier = Modifier,
    label: String? = stringResource(R.string.cyt_live_from_tv),
    placeholder: @Composable BoxScope.() -> Unit = { ThumbnailPlaceholder() },
) {
    val c = CytTheme.colors
    val shape = CytTheme.shapes.medium
    val reduced = CytTheme.reducedMotion
    Box(
        modifier.fillMaxWidth().aspectRatio(16f / 9f).clip(shape).background(Color.Black).border(1.dp, c.rim, shape)
            .semantics(mergeDescendants = true) { this.contentDescription = contentDescription; role = Role.Image },
    ) {
        FrameCrossfade(image, reduced, placeholder)
        if (label != null) {
            Text(
                label,
                Modifier.align(Alignment.TopEnd).padding(10.dp).background(Color.Black.copy(alpha = 0.6f), CytTheme.shapes.small).padding(horizontal = 8.dp, vertical = 3.dp),
                color = Color(0xFFA1A1A6), style = CytTheme.type.bodySmall,
            )
        }
    }
}

// The crossfade: the last frame stays underneath while the new one fades in over it. Each frame
// is one plain draw, so ModulateAlpha applies and no offscreen buffer is used (D-W7-7), unlike
// Crossfade's saveLayer. A frame that goes away (null) shows the placeholder at once.
@Composable
private fun BoxScope.FrameCrossfade(image: ImageBitmap?, reduced: Boolean, placeholder: @Composable BoxScope.() -> Unit) {
    var previous by remember { mutableStateOf<ImageBitmap?>(null) }
    var current by remember { mutableStateOf(image) }
    val alpha = remember { Animatable(1f) }
    LaunchedEffect(image) {
        if (image === current) return@LaunchedEffect
        previous = current
        current = image
        if (reduced || image == null) {
            alpha.snapTo(1f)
        } else {
            alpha.snapTo(0f)
            alpha.animateTo(1f, tween(CytMotion.THUMBNAIL_CROSSFADE_MS))
        }
        previous = null
    }
    val under = previous
    val top = current
    if (under != null && top != null) Image(under, null, Modifier.fillMaxSize(), contentScale = ContentScale.Crop)
    if (top != null) {
        Image(
            top, null,
            Modifier.fillMaxSize().graphicsLayer { this.alpha = alpha.value; compositingStrategy = CompositingStrategy.ModulateAlpha },
            contentScale = ContentScale.Crop,
        )
    } else {
        placeholder()
    }
}

@Composable
private fun BoxScope.ThumbnailPlaceholder() {
    val c = CytTheme.colors
    Box(Modifier.fillMaxSize().ambientGlow(c.glowTv, coreAlpha = 0.18f, midAlpha = 0.06f), contentAlignment = Alignment.Center) {
        CytIcon(CytIcons.Tv, null, tint = Color(0xFF98989E), size = 32.dp)
    }
}
